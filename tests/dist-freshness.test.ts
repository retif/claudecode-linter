import { describe, it, expect } from "vitest";
import { mkdtempSync, mkdirSync, rmSync, writeFileSync, utimesSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";
import {
	listTsSources,
	findStaleDistReason,
	assertDistFresh,
} from "./helpers/dist-freshness.js";

/**
 * Builds a throwaway repo layout. `sources` are written under src/, `outputs`
 * under dist/. mtimes are set explicitly rather than relying on write order,
 * so the staleness comparison is tested rather than the filesystem's timing.
 */
function makeTree(opts: {
	sources: string[];
	outputs?: string[];
	srcMtime?: number;
	distMtime?: number;
	noDist?: boolean;
}): string {
	const root = mkdtempSync(join(tmpdir(), "dist-freshness-test-"));
	const write = (base: string, rel: string, mtimeSec: number) => {
		const full = join(root, base, rel);
		mkdirSync(join(full, ".."), { recursive: true });
		writeFileSync(full, "// generated by a test\n");
		utimesSync(full, mtimeSec, mtimeSec);
	};
	for (const rel of opts.sources) write("src", rel, opts.srcMtime ?? 1_000);
	if (!opts.noDist) {
		mkdirSync(join(root, "dist"), { recursive: true });
		for (const rel of opts.outputs ?? opts.sources.map((s) => s.replace(/\.ts$/, ".js")))
			write("dist", rel, opts.distMtime ?? 2_000);
	}
	return root;
}

describe("listTsSources", () => {
	it("finds sources recursively and ignores .d.ts and non-TypeScript files", () => {
		const root = makeTree({
			sources: ["index.ts", "utils/kebab.ts", "types.d.ts", "notes.md"],
			outputs: [],
		});
		try {
			expect(listTsSources(join(root, "src"))).toEqual([
				"index.ts",
				join("utils", "kebab.ts"),
			]);
		} finally {
			rmSync(root, { recursive: true });
		}
	});

	it("returns an empty list for a src/ that does not exist", () => {
		const root = mkdtempSync(join(tmpdir(), "dist-freshness-test-"));
		try {
			expect(listTsSources(join(root, "src"))).toEqual([]);
		} finally {
			rmSync(root, { recursive: true });
		}
	});
});

describe("findStaleDistReason", () => {
	it("reports no reason when every output is newer than its source", () => {
		const root = makeTree({ sources: ["index.ts", "utils/kebab.ts"] });
		try {
			expect(findStaleDistReason(root)).toBeNull();
		} finally {
			rmSync(root, { recursive: true });
		}
	});

	it("detects a source edited after the build, naming the file and the fix", () => {
		const root = makeTree({
			sources: ["index.ts"],
			srcMtime: 3_000,
			distMtime: 2_000,
		});
		try {
			const reason = findStaleDistReason(root);
			expect(reason).toContain("src/index.ts");
			expect(reason).toContain("npm run build");
		} finally {
			rmSync(root, { recursive: true });
		}
	});

	it("detects a source edited in a subdirectory, not just at the top level", () => {
		const root = makeTree({ sources: ["index.ts", "utils/kebab.ts"] });
		try {
			utimesSync(join(root, "src", "utils", "kebab.ts"), 9_000, 9_000);
			expect(findStaleDistReason(root)).toContain(
				join("src", "utils", "kebab.ts"),
			);
		} finally {
			rmSync(root, { recursive: true });
		}
	});

	it("detects a missing dist/ directory", () => {
		const root = makeTree({ sources: ["index.ts"], noDist: true });
		try {
			expect(findStaleDistReason(root)).toContain("dist/ does not exist");
		} finally {
			rmSync(root, { recursive: true });
		}
	});

	it("detects a new source that has never been compiled", () => {
		const root = makeTree({ sources: ["index.ts", "brand-new.ts"], outputs: ["index.js"] });
		try {
			expect(findStaleDistReason(root)).toContain("dist/brand-new.js is missing");
		} finally {
			rmSync(root, { recursive: true });
		}
	});
});

describe("assertDistFresh", () => {
	it("does not throw when the build is current", () => {
		const root = makeTree({ sources: ["index.ts"] });
		try {
			expect(() => assertDistFresh(root)).not.toThrow();
		} finally {
			rmSync(root, { recursive: true });
		}
	});

	it("throws the staleness reason when the build is not current", () => {
		const root = makeTree({
			sources: ["index.ts"],
			srcMtime: 3_000,
			distMtime: 2_000,
		});
		try {
			expect(() => assertDistFresh(root)).toThrow(/npm run build/);
		} finally {
			rmSync(root, { recursive: true });
		}
	});
});
